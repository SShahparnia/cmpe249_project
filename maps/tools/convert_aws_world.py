#!/usr/bin/env python3
"""Convert an AWS RoboMaker Gazebo Classic world to Ignition Fortress (Module 10 step 1).

    python3 maps/tools/convert_aws_world.py maps/m1_house/aws_world/worlds/small_house.world \
        --name m1_house --floor -12 12 -8 9
    python3 maps/tools/convert_aws_world.py \
        maps/m3_warehouse/aws_world/worlds/no_roof_small_warehouse/no_roof_small_warehouse.world \
        --name m3_warehouse --floor -9 9 -13 13

Writes maps/<name>/<name>.sdf. This is option (b) of Module 3 step 2 ("convert the SDF
and models yourself"); no maintained Fortress port of these worlds exists. The meshes are
used unchanged from the pinned submodule (maps/<map>/aws_world/models, on the resource
path through harness/launch/tb4_sim.launch.py), because Fortress loads the COLLADA files
as they are. Only the world file is new:

  - world name = <name>, so the TB4 bridges find /world/<name>/...
  - Classic <physics type="ode"> and other Classic-only world elements are replaced by the
    physics block and system plugins of the TB4 Fortress worlds (identical on every map);
  - each Classic wrapper <model name=N><include>uri</include><pose>P</pose></model> is
    replaced by the included model's own SDF, inlined: named N, at pose P, static, with
    every <inertial> removed (sdformat rejects the whole world over one invalid inertia, and
    two house models have a zero principal moment; static models never use inertia). Mesh
    URIs stay model://... Every model is static, so nothing in the world can be pushed and
    the ground truth stays valid for the whole run;
  - lights and the scene's ambient / background colours are copied;
  - a ground plane is added at z = 0: collision plane, visual floor of 2 m tiles over
    --floor X0 X1 Y0 Y1 (the TB4's cliff sensors miss one big floor surface under software
    rendering, maps/tools/floor.py). It is never an obstacle at lidar height.

Commented-out models in the source stay out. The output is deterministic.
"""
from __future__ import annotations

import argparse
import copy
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from floor import floor_tiles_xml  # noqa: E402

HEAD ="""<?xml version="1.0"?>
<!-- Generated by maps/tools/convert_aws_world.py from {src}. Do not edit by hand. -->
<sdf version="1.6">
  <world name="{name}">
    <scene>
      <grid>false</grid>
{scene}    </scene>
    <physics name="1ms" type="ignored">
      <max_step_size>0.003</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin name='ignition::gazebo::systems::Physics' filename='libignition-gazebo-physics-system.so'/>
    <plugin name='ignition::gazebo::systems::UserCommands' filename='libignition-gazebo-user-commands-system.so'/>
    <plugin name='ignition::gazebo::systems::SceneBroadcaster' filename='libignition-gazebo-scene-broadcaster-system.so'/>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
        </collision>
        <!-- Visual floor: 2 m tiles, not one big surface (cliff sensors, see maps/tools/floor.py). -->
{floor}      </link>
    </model>

"""
TAIL = """  </world>
</sdf>
"""


def _norm_pose(text: str | None) -> str:
    vals = [float(v) for v in (text or "").split()] + [0.0] * 6
    return " ".join(f"{v:.6f}".rstrip("0").rstrip(".") if v != 0 else "0" for v in vals[:6])


def _strip_frame_attrs(el):
    for p in el.iter("pose"):
        for attr in ("frame", "relative_to"):
            if p.get(attr) in ("", None):
                p.attrib.pop(attr, None)
    return el


def _indent_xml(el, level: int) -> str:
    _strip_frame_attrs(el)
    text = ET.tostring(el, encoding="unicode").strip()
    text = re.sub(r"\n\s*\n", "\n", text)
    pad = "  " * level
    return "\n".join(pad + line.strip() if i == 0 else pad + line.rstrip() for i, line in enumerate(text.splitlines())) + "\n"


def find_models_dir(src: str) -> str:
    """The `models` folder of the AWS repo the world file belongs to (searched upwards)."""
    d = os.path.dirname(os.path.abspath(src))
    while True:
        if os.path.isdir(os.path.join(d, "models")):
            return os.path.join(d, "models")
        parent = os.path.dirname(d)
        if parent == d:
            raise FileNotFoundError(f"no models/ folder above {src}")
        d = parent


def inline_model(uri: str, name: str, pose: str, models_dir: str):
    """The included model's own <model>, renamed, posed, static, with every <inertial>
    removed. The models are static, so inertia never matters, but sdformat rejects the
    whole world over one invalid inertia (two house models have a zero principal moment).
    Mesh URIs stay model://... and resolve through the resource path as before."""
    if not uri.startswith("model://"):
        raise ValueError(f"{name}: only model:// includes are supported, got {uri}")
    mdir = os.path.join(models_dir, uri[len("model://"):].strip("/"))
    root = ET.parse(os.path.join(mdir, "model.sdf")).getroot()
    model = copy.deepcopy(root.find("model") if root.tag == "sdf" else root)
    own = model.find("pose")
    if own is not None and any(abs(float(v)) > 1e-9 for v in own.text.split()):
        # Classic applies the wrapper pose on top of this one; replacing it would move the model.
        raise NotImplementedError(f"{uri}: non-zero model pose {own.text.strip()!r} (compose it with {pose!r})")
    model.set("name", name)
    for parent in list(model.iter()):
        for child in list(parent):
            if child.tag in ("inertial", "pose", "static") and parent is model:
                parent.remove(child)
            elif child.tag == "inertial":
                parent.remove(child)
    p = ET.Element("pose")
    p.text = pose
    s = ET.Element("static")
    s.text = "true"
    model.insert(0, s)
    model.insert(0, p)
    return model


def convert(src: str, name: str, floor=(-15.0, 15.0, -15.0, 15.0), exclude=()) -> tuple[str, dict]:
    models_dir = find_models_dir(src)
    root = ET.parse(src).getroot()
    w = root.find("world")
    if w is None:
        raise ValueError(f"{src}: no <world>")
    stats = {"includes": 0, "raw_models": 0, "lights": 0, "excluded": []}

    scene = ""
    sc = w.find("scene")
    if sc is not None:
        for tag in ("ambient", "background"):
            v = sc.findtext(tag)
            if v:
                scene += f"      <{tag}>{v.strip()}</{tag}>\n"

    body = []
    used_names = set()
    for m in w.findall("model"):
        mname = m.get("name", "model")
        if any(re.search(rx, mname) for rx in exclude):
            stats["excluded"].append(mname)
            continue
        inc = m.find("include")
        if inc is not None and m.find("link") is None and m.find("model") is None:
            if inc.find("pose") is not None and m.find("pose") is not None:
                raise NotImplementedError(f"{mname}: pose on both the wrapper and the include")
            uri = inc.findtext("uri").strip()
            pose = _norm_pose(m.findtext("pose") if m.find("pose") is not None else inc.findtext("pose"))
            if mname in used_names:
                raise ValueError(f"duplicate model name {mname}")
            used_names.add(mname)
            body.append(_indent_xml(inline_model(uri, mname, pose, models_dir), 2))
            stats["includes"] += 1
        else:
            m2 = copy.deepcopy(m)
            st = m2.find("static")
            if st is None:
                st = ET.SubElement(m2, "static")
            st.text = "true"
            body.append(_indent_xml(m2, 2))
            stats["raw_models"] += 1
    for inc in w.findall("include"):
        body.append(_indent_xml(copy.deepcopy(inc), 2))
        stats["includes"] += 1
    lights = []
    for lt in w.findall("light"):
        lights.append(_indent_xml(copy.deepcopy(lt), 2))
        stats["lights"] += 1

    rel = os.path.relpath(src, os.path.join(HERE, "..")).replace(os.sep, "/")
    out = (HEAD.format(src=rel, name=name, scene=scene, floor=floor_tiles_xml(*floor, color="0.7 0.7 0.7 1"))
           + "".join(body) + "\n" + "".join(lights) + TAIL)
    return out, stats


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("src", help="Classic .world file")
    ap.add_argument("--name", required=True, help="map name (Section 0.1), also the world name")
    ap.add_argument("--floor", type=float, nargs=4, required=True, metavar=("X0", "X1", "Y0", "Y1"),
                    help="world rectangle covered by the visual floor tiles (the building plus ~2 m)")
    ap.add_argument("--exclude", action="append", default=[], help="regex on model names to drop")
    ap.add_argument("--out", help="default: maps/<name>/<name>.sdf")
    a = ap.parse_args(argv)
    text, stats = convert(a.src, a.name, tuple(a.floor), a.exclude)
    out = a.out or os.path.join(HERE, "..", a.name, f"{a.name}.sdf")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(out)}: {stats['includes']} included models inlined, {stats['raw_models']} models copied, "
          f"{stats['lights']} lights" + (f", excluded {stats['excluded']}" if stats["excluded"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
