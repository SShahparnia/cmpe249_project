#!/usr/bin/env python3
"""Generate the M2 office-corridor world (Module 10 step 2; Module 21 for the 2x copy).

    python3 maps/tools/make_office.py                          # maps/m2_office/m2_office.sdf
    python3 maps/tools/make_office.py --copies 2 --name m2_office_2x

One layout unit is 12 m x 10.3 m: a 2 m corridor along x, three 4 m rooms to the north
and two 6 m rooms to the south, each opening onto the corridor through a 0.9 m doorway.
The middle and east north rooms also connect through an inner door, so the robot can
loop. Furniture is solid boxes, so every piece crosses the lidar plane the same way in
Gazebo and in the ground truth. `--copies k` repeats the unit k times along x
(Module 21: "repeat the layout, do not redesign it"); the corridor runs straight through.

The building is centred on the world origin, so the default spawn (0, 0) is in the
corridor. Everything is deterministic: the same arguments always write the same file.

The world uses the same physics block and system plugins as the TB4 Fortress worlds
(turtlebot4_ignition_bringup/worlds/warehouse.sdf). After the prereg-v1 tag the output
is frozen (maps/m2_office/README.md).
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from floor import floor_tiles_xml  # noqa: E402

UNIT_L = 12.0           # m along x per copy
CORR_HALF = 1.0         # corridor is y in [-1, 1]
ROOM_D = 4.0            # room depth (north: y 1..5, south: y -5..-1)
WALL_T = 0.15
WALL_H = 2.0
DOOR_W = 0.9

# Per unit, x relative to the unit's west edge.
NORTH_ROOMS = [(0.0, 4.0), (4.0, 8.0), (8.0, 12.0)]
SOUTH_ROOMS = [(0.0, 6.0), (6.0, 12.0)]
NORTH_DOORS = [1.0, 5.5, 9.0]          # doorway start x (corridor side)
SOUTH_DOORS = [4.5, 7.0]
INNER_DOOR_Y = 2.4                      # doorway between north rooms 2 and 3, start y
# Furniture: (name, cx, cy, sx, sy, sz), unit-relative x, absolute y.
FURNITURE = [
    # north room 1: two desks and a cabinet
    ("desk_n1a", 1.2, 4.3, 1.4, 0.7, 0.75), ("desk_n1b", 3.0, 3.0, 0.7, 1.4, 0.75),
    ("cab_n1", 0.35, 2.6, 0.5, 1.0, 1.2),
    # north room 2: meeting table
    ("table_n2", 6.0, 3.2, 2.0, 1.0, 0.75),
    # north room 3: desk row and a bookshelf
    ("desk_n3a", 9.0, 4.4, 1.4, 0.7, 0.75), ("desk_n3b", 10.8, 4.4, 1.4, 0.7, 0.75),
    ("shelf_n3", 11.65, 2.5, 0.4, 1.6, 1.8),
    # south room 1 (open plan): desk islands and a column
    ("island_s1a", 1.8, -3.2, 2.4, 1.2, 0.75), ("island_s1b", 4.2, -4.3, 1.2, 0.8, 0.75),
    ("column_s1", 3.0, -2.2, 0.4, 0.4, WALL_H),
    # south room 2: storage racks
    ("rack_s2a", 8.0, -4.55, 3.0, 0.6, 1.8), ("rack_s2b", 10.5, -2.8, 0.6, 2.0, 1.8),
    # corridor: one cabinet in a recess-free spot, narrows the corridor to 1.6 m
    ("cab_corr", 3.0, -0.8, 1.0, 0.4, 1.0),
]

WORLD_HEAD = """<?xml version="1.0"?>
<!-- Generated by maps/tools/make_office.py {args}. Do not edit by hand. -->
<sdf version="1.6">
  <world name="{name}">
    <scene>
      <grid>false</grid>
    </scene>
    <physics name="1ms" type="ignored">
      <max_step_size>0.003</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin name='ignition::gazebo::systems::Physics' filename='libignition-gazebo-physics-system.so'/>
    <plugin name='ignition::gazebo::systems::UserCommands' filename='libignition-gazebo-user-commands-system.so'/>
    <plugin name='ignition::gazebo::systems::SceneBroadcaster' filename='libignition-gazebo-scene-broadcaster-system.so'/>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -1</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>100 100</size></plane></geometry>
        </collision>
        <!-- Visual floor: 2 m tiles, not one big surface (cliff sensors, see maps/tools/floor.py). -->
{floor}      </link>
    </model>

    <model name="office">
      <static>true</static>
      <link name="link">
"""
WORLD_TAIL = """      </link>
    </model>
  </world>
</sdf>
"""
COLORS = {"wall": "0.85 0.83 0.78 1", "furniture": "0.45 0.33 0.22 1", "column": "0.6 0.6 0.6 1"}


def box(name, cx, cy, sx, sy, sz, color):
    g = f"<geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>"
    return (f"        <collision name=\"{name}_c\"><pose>{cx:.3f} {cy:.3f} {sz / 2:.3f} 0 0 0</pose>{g}</collision>\n"
            f"        <visual name=\"{name}_v\"><pose>{cx:.3f} {cy:.3f} {sz / 2:.3f} 0 0 0</pose>{g}"
            f"<material><ambient>{color}</ambient><diffuse>{color}</diffuse></material></visual>\n")


def wall_x(name, x0, x1, y, gaps=()):
    """Wall along x from x0 to x1 at y, with doorway gaps [(gx0, gx1), ...]."""
    out, cur = [], x0
    for g0, g1 in sorted(gaps):
        if g0 > cur:
            out.append((f"{name}_{len(out)}", cur, g0, y))
        cur = g1
    if cur < x1:
        out.append((f"{name}_{len(out)}", cur, x1, y))
    return [box(n, (a + b) / 2, yy, b - a, WALL_T, WALL_H, COLORS["wall"]) for n, a, b, yy in out]


def wall_y(name, y0, y1, x, gaps=()):
    out, cur = [], y0
    for g0, g1 in sorted(gaps):
        if g0 > cur:
            out.append((f"{name}_{len(out)}", cur, g0, x))
        cur = g1
    if cur < y1:
        out.append((f"{name}_{len(out)}", cur, y1, x))
    return [box(n, xx, (a + b) / 2, WALL_T, b - a, WALL_H, COLORS["wall"]) for n, a, b, xx in out]


def build(copies: int) -> list:
    total = UNIT_L * copies
    west = -total / 2
    y_n, y_s = CORR_HALF + ROOM_D, -CORR_HALF - ROOM_D
    parts = []
    # Outer shell (half a wall thickness of overlap at the corners keeps it closed).
    h = WALL_T / 2
    parts += wall_x("outer_n", west - h, west + total + h, y_n)
    parts += wall_x("outer_s", west - h, west + total + h, y_s)
    parts += wall_y("outer_w", y_s, y_n, west)
    parts += wall_y("outer_e", y_s, y_n, west + total)
    for k in range(copies):
        x0 = west + k * UNIT_L
        tag = f"u{k}"
        n_gaps = [(x0 + d, x0 + d + DOOR_W) for d in NORTH_DOORS]
        s_gaps = [(x0 + d, x0 + d + DOOR_W) for d in SOUTH_DOORS]
        parts += wall_x(f"{tag}_corr_n", x0, x0 + UNIT_L, CORR_HALF, n_gaps)
        parts += wall_x(f"{tag}_corr_s", x0, x0 + UNIT_L, -CORR_HALF, s_gaps)
        # Partitions between rooms (not on the unit's outer edges: those are the shell or
        # the neighbouring unit's partition at the same x).
        for i, (a, _b) in enumerate(NORTH_ROOMS):
            if a > 0:
                gaps = [(INNER_DOOR_Y, INNER_DOOR_Y + DOOR_W)] if i == 2 else []
                parts += wall_y(f"{tag}_part_n{i}", CORR_HALF, y_n, x0 + a, gaps)
        for i, (a, _b) in enumerate(SOUTH_ROOMS):
            if a > 0:
                parts += wall_y(f"{tag}_part_s{i}", y_s, -CORR_HALF, x0 + a)
        if k > 0:   # boundary between units, north and south rooms
            parts += wall_y(f"{tag}_part_n0", CORR_HALF, y_n, x0)
            parts += wall_y(f"{tag}_part_s0", y_s, -CORR_HALF, x0)
        for name, cx, cy, sx, sy, sz in FURNITURE:
            color = COLORS["column"] if name.startswith("column") else COLORS["furniture"]
            parts.append(box(f"{tag}_{name}", x0 + cx, cy, sx, sy, sz, color))
    return parts


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--copies", type=int, default=1)
    ap.add_argument("--name", default="m2_office")
    ap.add_argument("--out", help="default: maps/<name>/<name>.sdf")
    a = ap.parse_args(argv)
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", a.name, f"{a.name}.sdf")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    args = f"(copies={a.copies}, name={a.name})"
    with open(out, "w", newline="\n") as f:
        half_x, half_y = UNIT_L * a.copies / 2 + 2.0, CORR_HALF + ROOM_D + 2.0
        f.write(WORLD_HEAD.format(name=a.name, args=args, floor=floor_tiles_xml(-half_x, half_x, -half_y, half_y)))
        f.writelines(build(a.copies))
        f.write(WORLD_TAIL)
    print(f"wrote {os.path.normpath(out)} ({UNIT_L * a.copies:.0f} m x {2 * (CORR_HALF + ROOM_D):.0f} m)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
