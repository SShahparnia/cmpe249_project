#!/usr/bin/env python3
"""Write docs/pilot_report.md from the Block P runs (Module 17).

    python3 analysis/pilot_report.py [logs] [--out docs/pilot_report.md]

Contents (instructions.md Module 17 "Done when"): every pilot result, the sd estimates,
the sample-size numbers and the decision, plus the numbers the pilot fixes for
configs/common.yaml before prereg-v1:

  timeout_sim_s     about 2x the slowest completed pilot run (rounded up to a minute)
  replan_period_s   decision latency per method (median, p95) on the pilot machines
  oscillation X     oscillation counts at several thresholds, per method
  wall time / run   median and max per map, and what Block Q costs at that rate

Suggested values are suggestions: the team decides and edits configs/common.yaml.
"""
from __future__ import annotations

import argparse
import datetime as dt
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
import coverage as cov  # noqa: E402
from load import load_cycles, load_runs, read_csv  # noqa: E402
from sample_size import analyse  # noqa: E402

PLANNED = 27
X_CANDIDATES = (0.5, 1.0, 1.5, 2.0, 3.0)


def fmt(v, nd=2):
    if v is None or (isinstance(v, float) and not math.isfinite(v)):
        return "–"
    return f"{v:.{nd}f}" if isinstance(v, (float, np.floating)) else str(v)


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def oscillations(run_dir, x):
    g = read_csv(os.path.join(run_dir, "goals.csv"))
    n = read_csv(os.path.join(run_dir, "nav2_results.csv"))
    if g.empty:
        return 0
    return cov.oscillation_count(g["t_ros"].to_numpy(), g[["goal_x", "goal_y"]].to_numpy(),
                                 n["t_ros"].to_numpy() if not n.empty else np.array([]),
                                 n["status"].to_numpy() if not n.empty else np.array([]), x)


def build(logs, block="P") -> str:
    runs = load_runs(logs, block)
    lines = ["# Pilot report (Module 17)", "",
             f"Generated by `analysis/pilot_report.py` on {dt.date.today().isoformat()} from `{os.path.relpath(logs, REPO)}`, "
             f"Block {block}. Pilot runs are not part of the main results.", ""]
    if runs.empty:
        lines.append(f"No Block {block} runs found.")
        return "\n".join(lines) + "\n"

    oc = runs["outcome"].value_counts().to_dict()
    lines += [f"**Runs:** {len(runs)} of {PLANNED} planned. Outcomes: "
              + ", ".join(f"{k} {v}" for k, v in sorted(oc.items())) + ".", ""]
    if oc.get("invalid"):
        lines += ["Invalid runs are reruns, not data: check that each has a valid rerun and a row in `docs/run_log.md`.", ""]

    # 1. every result
    lines += ["## 1. Results", ""]
    rows = [[r.map, r.pose, r.method, r.outcome, r.d_95, r.t_95, r.final_coverage, r.total_distance_m,
             r.wall_duration_s, r.rtf, r.latency_p95_s] for r in runs.itertuples()]
    lines += [md_table(["map", "pose", "method", "outcome", "d_95 (m)", "t_95 (s)", "final cov.", "distance (m)",
                        "wall (s)", "RTF", "latency p95 (s)"], rows), ""]

    # 2. sample size
    data = runs[runs["outcome"] != "invalid"]
    res = analyse(data)
    lines += ["## 2. Sample size", "",
              "Relative paired difference r = (d_95[method] − d_95[nearest]) / d_95[nearest] per (map, pose), "
              "pooled over the three maps. `analysis/sample_size.py`: two-sided Wilcoxon, α = 0.05/3 (Holm worst case), "
              f"power 0.8, δ = {res['delta']:.2f}, ARE 0.864; n_safe uses the 80% upper bound on the sd. "
              "Runs without 95% coverage use their total distance (flagged).", ""]
    srows = []
    for m, v in res["methods"].items():
        if "n_safe" not in v:
            srows.append([m, v["n_pairs"], "–", "–", "–", "–", "–", v.get("note", "")])
            continue
        per_map = "; ".join(f"{k}: {fmt(pm['sd_r'], 3)}" for k, pm in v["per_map"].items())
        srows.append([m, v["n_pairs"], v["n_censored"], fmt(v["mean_r"], 3), fmt(v["sd_r_pooled"], 3),
                      v["n_point"], v["n_safe"], per_map])
    lines += [md_table(["method", "pairs", "censored", "mean r", "pooled sd(r)", "n_point", "n_safe", "sd(r) per map"],
                       srows), "", "**Decision rule (plan.md):** if 10 poses per map are enough, Block Q stays at 10 and "
              "the ablation stays in; otherwise Block Q goes to 15 and the ablation is dropped.", "",
              f"**Result:** n_safe (largest over methods) = {res['n_safe_max']}. → {res['decision']}.", "",
              "If the per-map sds differ a lot (one map several times the others), pool only the similar maps and "
              "say so here.", ""]

    # 3. settings fixed by the pilot
    comp = data[data["outcome"] == "complete"]
    lines += ["## 3. Settings fixed by the pilot (update `configs/common.yaml`)", ""]
    if len(comp):
        slow = float(comp["t_95"].max())
        sugg = int(math.ceil(2 * slow / 60.0) * 60)
        lines += [f"**timeout_sim_s:** slowest completed pilot run reached 95% at {slow:.0f} s sim time "
                  f"({comp.loc[comp['t_95'].idxmax(), 'run_id']}). 2× that, rounded up to a minute: **{sugg} s**.", ""]
    else:
        lines += ["**timeout_sim_s:** no run completed; cannot set it from the pilot.", ""]

    cyc = load_cycles(data)
    if not cyc.empty:
        lat = cyc.groupby("method", observed=True)["latency_s"]
        lrows = [[m, len(g), 1000 * g.median(), 1000 * g.quantile(0.95), 1000 * g.max()] for m, g in lat]
        worst = max(r[3] for r in lrows) / 1000.0
        lines += ["**replan_period_s:** decision latency per planning cycle on the pilot machines (wall clock):", "",
                  md_table(["method", "cycles", "median (ms)", "p95 (ms)", "max (ms)"], lrows), "",
                  f"Largest p95 = {worst * 1000:.0f} ms. Keep **1.0 s** if every p95 stays well below it "
                  "(the Jetson is slower than the laptop: Block E latencies will be higher, which is what H2 measures); "
                  "otherwise choose 2.0 s. The deadline-miss rate is reported against this value.", ""]

    orows = []
    for m, g in data.groupby("method", observed=True):
        counts = [np.mean([oscillations(d, x) for d in g["dir"]]) for x in X_CANDIDATES]
        orows.append([m] + [round(c, 2) for c in counts])
    lines += ["**Oscillation threshold X:** mean oscillation count per run at each candidate X "
              "(a goal switch farther than X while the current goal is neither reached nor aborted):", "",
              md_table(["method"] + [f"X = {x} m" for x in X_CANDIDATES], orows), "",
              "Pick the smallest X above which counts stop dropping quickly (re-targeting within one frontier "
              "falls below it); 1.0 m unless the table says otherwise.", ""]

    if data["wall_duration_s"].notna().any():
        wt = data.groupby("map")["wall_duration_s"]
        wrows = [[mp, len(g), g.median() / 60, g.max() / 60] for mp, g in wt]
        per_run = float(data["wall_duration_s"].median()) / 60.0
        lines += ["**Wall time per run** (for the Module 19 schedule):", "",
                  md_table(["map", "runs", "median (min)", "max (min)"], wrows), "",
                  f"Block Q at 10 poses: 3 methods × 3 maps × 10 = 90 runs ≈ {90 * per_run / 60:.1f} h at the median; "
                  f"at 15 poses: 135 runs ≈ {135 * per_run / 60:.1f} h (plus setup and invalid reruns).", ""]

    lines += ["## 4. Sign-off", "", "| member | date | agrees with the decision |", "|---|---|---|",
              "| Shervan | | |", "| Joey | | |", "| Aaron | | |", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("logs", nargs="?", default=os.path.join(REPO, "logs"))
    ap.add_argument("--block", default="P")
    ap.add_argument("--out", default=os.path.join(REPO, "docs", "pilot_report.md"))
    a = ap.parse_args(argv)
    text = build(a.logs, a.block)
    with open(a.out, "w", newline="\n", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
